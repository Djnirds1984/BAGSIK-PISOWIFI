#!/usr/bin/env bash
#
# BAGSIK PISOWIFI - appliance installer.
#
# Turns a fresh Debian/Ubuntu/Raspberry Pi OS/Armbian box (any SBC or x86
# mini PC) into a coin-operated Wi-Fi vending machine:
#   * access point        -> hostapd
#   * DHCP + DNS          -> dnsmasq
#   * routing + NAT       -> nftables
#   * vouchers/portal/app -> this repository, run by systemd
#
# Usage, from the repository root, as root:
#   sudo LAN_IFACE=wlan0 WAN_IFACE=eth0 ./deploy/install.sh
#
# LAN_IFACE is the interface that serves customers (usually the Wi-Fi radio,
# or a USB Wi-Fi dongle). WAN_IFACE is the uplink. Both default to
# auto-detection: the default-route NIC is WAN, the other one is LAN.

set -euo pipefail

APP_DIR="${APP_DIR:-/opt/bagsik}"
ETC_DIR="${ETC_DIR:-/etc/bagsik}"
DATA_DIR="${DATA_DIR:-/var/lib/bagsik}"
SVC_USER="${SVC_USER:-bagsik}"
LAN_IFACE="${LAN_IFACE:-}"
WAN_IFACE="${WAN_IFACE:-}"
LAN_IP="${LAN_IP:-10.0.0.1}"
WLAN_PASSWORD="${WLAN_PASSWORD:-bagsikwifi}"

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

say()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31mxx\033[0m %s\n' "$*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || die "run this with sudo"

# --------------------------------------------------------------------------
# 1. Interface discovery
# --------------------------------------------------------------------------
if [[ -z "$WAN_IFACE" ]]; then
  WAN_IFACE="$(ip -4 route show default | awk '/default/ {print $5; exit}')"
fi
if [[ -z "$LAN_IFACE" ]]; then
  for candidate in $(ls /sys/class/net); do
    [[ "$candidate" == "lo" || "$candidate" == "$WAN_IFACE" ]] && continue
    [[ -d "/sys/class/net/$candidate/wireless" ]] && LAN_IFACE="$candidate" && break
  done
fi
if [[ -z "$LAN_IFACE" ]]; then
  for candidate in $(ls /sys/class/net); do
    [[ "$candidate" == "lo" || "$candidate" == "$WAN_IFACE" ]] && continue
    LAN_IFACE="$candidate" && break
  done
fi
[[ -n "$LAN_IFACE" && -n "$WAN_IFACE" ]] || die "could not detect LAN/WAN - pass LAN_IFACE= and WAN_IFACE="
[[ "$LAN_IFACE" != "$WAN_IFACE" ]] || die "LAN and WAN are the same interface ($LAN_IFACE)"

LAN_CIDR="${LAN_IP}/24"
LAN_PREFIX="${LAN_IP%.*}"
LAN_START="${LAN_PREFIX}.10"
LAN_END="${LAN_PREFIX}.250"

say "LAN $LAN_IFACE ($LAN_CIDR)   WAN $WAN_IFACE"

# --------------------------------------------------------------------------
# 2. Packages
# --------------------------------------------------------------------------
say "installing packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq \
  python3 python3-venv python3-pip \
  hostapd dnsmasq nftables iproute2 iw rsync \
  rfkill ca-certificates

# Raspberry Pi OS ships NetworkManager on some images; it fights hostapd.
if systemctl is-enabled --quiet NetworkManager 2>/dev/null; then
  warn "NetworkManager is enabled - mark $LAN_IFACE as unmanaged if the AP keeps dropping"
fi

# --------------------------------------------------------------------------
# 3. Service account + application
# --------------------------------------------------------------------------
say "installing the application into $APP_DIR"
id -u "$SVC_USER" >/dev/null 2>&1 || useradd --system --home "$APP_DIR" --shell /usr/sbin/nologin "$SVC_USER"
install -d -m 0755 "$APP_DIR"
install -d -m 0750 -o "$SVC_USER" -g "$SVC_USER" "$DATA_DIR"
install -d -m 0750 "$ETC_DIR"

# Copy the tree without the dev-only bits, then reuse an existing venv.
rsync -a --delete \
  --exclude '.git' --exclude '.venv' --exclude '__pycache__' \
  --exclude 'data' --exclude '.pytest_cache' --exclude 'tests' \
  --exclude '.env' \
  "$REPO_DIR"/ "$APP_DIR"/

python3 -m venv "$APP_DIR/.venv"
"$APP_DIR/.venv/bin/pip" install --quiet --upgrade pip
"$APP_DIR/.venv/bin/pip" install --quiet -r "$APP_DIR/requirements.txt"

# The coin slot counts pulses through gpiozero. Only install it where a GPIO
# chip exists, so x86 boxes without one stay dependency-light.
if compgen -G "/dev/gpiochip*" >/dev/null; then
  "$APP_DIR/.venv/bin/pip" install --quiet gpiozero lgpio \
    || warn "gpiozero/lgpio install failed - set BAGSIK_COIN_DRIVER=mock for now"
fi
chown -R "$SVC_USER:$SVC_USER" "$APP_DIR"

# --------------------------------------------------------------------------
# 4. Application config
# --------------------------------------------------------------------------
ENV_FILE="$ETC_DIR/bagsik.env"
if [[ -f "$ENV_FILE" ]]; then
  say "keeping existing $ENV_FILE"
else
  say "writing $ENV_FILE"
  SECRET="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')"
  ADMIN_PASS="$(python3 -c 'import secrets,string; a=string.ascii_letters+string.digits; print("".join(secrets.choice(a) for _ in range(12)))')"
  cat > "$ENV_FILE" <<EOF
# BAGSIK PISOWIFI - generated by deploy/install.sh
BAGSIK_SECRET_KEY=$SECRET
BAGSIK_DB_PATH=$DATA_DIR/bagsik.db
BAGSIK_TIMEZONE=Asia/Manila
BAGSIK_PORTAL_URL=http://$LAN_IP

BAGSIK_ADMIN_USER=admin
BAGSIK_ADMIN_PASSWORD=$ADMIN_PASS
BAGSIK_SESSION_HOURS=12

BAGSIK_ROUTER_DRIVER=local
BAGSIK_LAN_IFACE=$LAN_IFACE
BAGSIK_WAN_IFACE=$WAN_IFACE
BAGSIK_LAN_CIDR=$LAN_CIDR
BAGSIK_ENFORCE_SECONDS=10

BAGSIK_COIN_DRIVER=gpio
BAGSIK_GPIO_PIN=17
BAGSIK_COIN_PULSE_CENTAVOS=100
BAGSIK_COIN_IDLE_SECONDS=1.2
BAGSIK_COIN_ARM_SECONDS=120

BAGSIK_DEV_MODE=false
EOF
  chmod 0640 "$ENV_FILE"
  chown root:"$SVC_USER" "$ENV_FILE"
fi

# --------------------------------------------------------------------------
# 5. Static address on the LAN interface (the box is the gateway)
# --------------------------------------------------------------------------
say "assigning $LAN_CIDR to $LAN_IFACE"
if command -v nmcli >/dev/null 2>&1 && nmcli -t -f NAME,DEVICE connection show --active 2>/dev/null | grep -q "$LAN_IFACE"; then
  CONN="$(nmcli -t -f NAME,DEVICE connection show --active | awk -F: -v d="$LAN_IFACE" '$2==d {print $1; exit}')"
  nmcli connection modify "$CONN" ipv4.method manual ipv4.addresses "$LAN_CIDR" ipv4.never-default yes
else
  ip addr replace "$LAN_CIDR" dev "$LAN_IFACE" || warn "could not set the address now - persistence is handled by hostapd/dnsmasq on boot"
fi

# Forwarding must survive reboots.
cat > /etc/sysctl.d/90-bagsik.conf <<EOF
net.ipv4.ip_forward=1
EOF
sysctl -q --system

# --------------------------------------------------------------------------
# 6. Access point, DHCP, NAT
# --------------------------------------------------------------------------
say "configuring hostapd (SSID 'BAGSIK PISOWIFI', WPA2)"
sed -e "s/__LAN__/$LAN_IFACE/g" -e "s/__WLAN_PASSWORD__/$WLAN_PASSWORD/g" \
  "$APP_DIR/deploy/hostapd.conf.example" > /etc/hostapd/hostapd.conf
chmod 0600 /etc/hostapd/hostapd.conf
sed -i 's|^#\?DAEMON_CONF=.*|DAEMON_CONF="/etc/hostapd/hostapd.conf"|' /etc/default/hostapd
rfkill unblock wifi || true

say "configuring dnsmasq"
sed -e "s/__LAN_IP__/$LAN_IP/g" \
    -e "s/__LAN_START__/$LAN_START/g" \
    -e "s/__LAN_END__/$LAN_END/g" \
    -e "s/__LAN__/$LAN_IFACE/g" \
  "$APP_DIR/deploy/dnsmasq.conf.example" > /etc/dnsmasq.d/bagsik.conf
# Debian's dnsmasq listens on all interfaces by default; we bind explicitly.
sed -i 's/^#\?bind-interfaces/bind-interfaces/' /etc/dnsmasq.conf || true

say "installing NAT rules"
sed -e "s/__LAN__/$LAN_IFACE/g" -e "s/__WAN__/$WAN_IFACE/g" -e "s/__LAN_CIDR__/$LAN_CIDR/g" \
  "$APP_DIR/deploy/nftables-bagsik-nat.nft" > /etc/nftables.d/bagsik-nat.nft
if ! grep -q 'bagsik-nat.nft' /etc/nftables.conf 2>/dev/null; then
  echo 'include "/etc/nftables.d/bagsik-nat.nft"' >> /etc/nftables.conf
fi

# --------------------------------------------------------------------------
# 7. systemd units
# --------------------------------------------------------------------------
say "installing systemd unit"
install -m 0644 "$APP_DIR/deploy/bagsik.service" /etc/systemd/system/bagsik.service
systemctl daemon-reload
systemctl unmask hostapd >/dev/null 2>&1 || true
systemctl enable --now nftables
nft -f /etc/nftables.d/bagsik-nat.nft
systemctl enable --now hostapd dnsmasq bagsik

# --------------------------------------------------------------------------
# 8. Report
# --------------------------------------------------------------------------
sleep 2
echo
say "BAGSIK PISOWIFI is installed"
echo "    SSID          : BAGSIK PISOWIFI"
echo "    Wi-Fi password: $WLAN_PASSWORD"
echo "    Portal        : http://$LAN_IP/"
echo "    Admin         : http://$LAN_IP/admin"
echo "    Credentials   : in $ENV_FILE (BAGSIK_ADMIN_USER / BAGSIK_ADMIN_PASSWORD)"
echo "    Database      : $DATA_DIR/bagsik.db"
echo
echo "    Logs          : journalctl -u bagsik -f"
echo "    Coin acceptor : gpio on GPIO17 (3.3V logic - use an optocoupler)"
echo "                    see INSTALL.md section 4 for wiring and testing"
echo "    Next steps    : systemctl status bagsik hostapd dnsmasq"
